if __name__ == '__main__':
    config = ConfigManager('/mnt/e/tools/movieTool/config.json')
    excel = ExcelManager(config.get_path_config()['excel_path'])

    # Build row-index lookup to avoid expensive find_row_by_path
    rows = list(excel.sheet.iter_rows(min_row=2))
    tag_col = excel._get_column_index('tags')
    actor_col = excel._get_column_index('actor')

    updated = 0
    skipped = set()
    for row in rows:
        actor = (row[actor_col].value or '').strip()
        if not actor:
            continue
        tags = ACTRESS_TAGS.get(actor)
        if not tags:
            skipped.add(actor)
            continue

        existing = (row[tag_col].value or '').strip()
        existing_set = set(t.strip() for t in existing.split(',') if t.strip())
        new_set = set(t.strip() for t in tags.split(',') if t.strip())
        merged = list(dict.fromkeys(list(new_set) + list(existing_set)))
        row[tag_col].value = ','.join(merged)
        updated += 1

    excel.save()
    print(f'Tagged: {updated} movies')
    if skipped:
        print(f'Skipped ({len(skipped)}): {sorted(skipped)[:10]}')
    print('Done.')
